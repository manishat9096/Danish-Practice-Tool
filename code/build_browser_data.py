"""Bundle the split vocabulary so the HTML also works when opened via file://."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATEGORIES = ('verbs', 'nouns', 'adjectives', 'adverbs', 'common_phrases')


def main():
    vocabulary = {}
    for category in CATEGORIES:
        payload = json.loads((ROOT / 'data' / f'{category}.json').read_text(encoding='utf-8-sig'))
        entries = payload if isinstance(payload, list) else payload[category]
        if not isinstance(entries, list):
            raise ValueError(f'{category} must contain an array')
        vocabulary[category] = entries
    content = json.dumps(vocabulary, ensure_ascii=False, separators=(',', ':'))
    (ROOT / 'data' / 'lexicon.browser.js').write_text(
        '// Generated by code/build_browser_data.py. Edit the category JSON files instead.\n'
        + 'window.DANISH_LEXICON = ' + content + ';\n', encoding='utf-8')
    print(f'Bundled {sum(map(len, vocabulary.values()))} vocabulary entries for the browser.')


if __name__ == '__main__':
    main()
